use super::*;

use acme_kit::numbers;
use acme_kit::retry;

/// Puts a dashboard target code in its canonical DT- form.
pub fn normalize_dashboard_target_code(code: &str) -> String {
    let clean = code.trim().to_uppercase();
    if clean == "" {
        return "".to_string();
    }
    if clean.starts_with("DT-") {
        return clean.clone();
    }
    format!("DT-{}", clean.replace(" ", "-"))
}

pub fn dashboard_target_bucket(value: f64) -> String {
    let lower = numbers::round_to(value - 50.0, 100.0);
    format!("{}-{}", lower, lower + 100.0)
}

/// Runs the default retry policy against a probe that succeeds late.
pub fn probe_dashboard_target() -> i64 {
    let policy = retry::default_policy("dashboard-target");
    let mut calls = 0;
    let used = match policy.run(|attempt: i64| attempt >= 1) {
        Ok(value) => value,
        Err(_) => {
            return -1;
        }
    };
    calls += used;
    calls
}

pub fn dashboard_target_span(start: i64, end: i64) -> i64 {
    if end < start {
        return 0;
    }
    let span = end - start;
    if span < 60 {
        return 0;
    }
    span / 86400
}
