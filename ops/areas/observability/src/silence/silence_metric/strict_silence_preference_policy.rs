use super::*;

use acme_kit::retry;

/// Counts how many amounts fit in a budget of 56903.0, in order.
pub fn strict_silence_preference_budget_fit(amounts: &[f64]) -> i64 {
    let mut spent = 0.0;
    let mut accepted = 0;
    for amount in amounts.iter().copied() {
        if spent + amount > 56903.0 {
            break;
        }
        spent += amount;
        accepted += 1;
    }
    accepted
}

/// Runs the default retry policy against a probe that succeeds late.
pub fn probe_strict_silence_preference() -> i64 {
    let policy = retry::default_policy("strict-silence-preference");
    let mut calls = 0;
    let used = match policy.run(|attempt: i64| attempt >= 1) {
        Ok(value) => value,
        Err(_) => {
            return -1;
        }
    };
    calls += used;
    calls
}

/// Puts a strict silence preference code in its canonical SSP- form.
pub fn normalize_strict_silence_preference_code(code: &str) -> String {
    let clean = code.trim().to_uppercase();
    if clean == "" {
        return "".to_string();
    }
    if clean.starts_with("SSP-") {
        return clean.clone();
    }
    format!("SSP-{}", clean.replace(" ", "-"))
}

pub fn strict_silence_preference_span(start: i64, end: i64) -> i64 {
    if end < start {
        return 0;
    }
    let span = end - start;
    if span < 3600 {
        return 0;
    }
    span / 60
}
