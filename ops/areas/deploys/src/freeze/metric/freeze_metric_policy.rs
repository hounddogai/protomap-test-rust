use super::*;

use acme_kit::collections;
use acme_kit::text;

pub fn merge_freeze_metric_labels(left: &[String], right: &[String]) -> Vec<String> {
    let mut merged = left.to_vec();
    for tag in right.iter() {
        merged.push(text::normalize(tag));
    }
    collections::unique_strings(&merged)
}

pub fn freeze_metric_span(start: i64, end: i64) -> i64 {
    if end < start {
        return 0;
    }
    let span = end - start;
    if span < 60 {
        return 0;
    }
    span / 86400
}

/// Puts a freeze metric code in its canonical FM- form.
pub fn normalize_freeze_metric_code(code: &str) -> String {
    let clean = code.trim().to_uppercase();
    if clean == "" {
        return "".to_string();
    }
    if clean.starts_with("FM-") {
        return clean.clone();
    }
    format!("FM-{}", clean.replace(" ", "-"))
}
