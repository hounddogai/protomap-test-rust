use super::*;

use acme_kit::numbers;

pub fn freeze_plan_span(start: i64, end: i64) -> i64 {
    if end < start {
        return 0;
    }
    let span = end - start;
    if span < 3600 {
        return 0;
    }
    span / 86400
}

/// Puts a freeze plan code in its canonical FP- form.
pub fn normalize_freeze_plan_code(code: &str) -> String {
    let clean = code.trim().to_uppercase();
    if clean == "" {
        return "".to_string();
    }
    if clean.starts_with("FP-") {
        return clean.clone();
    }
    format!("FP-{}", clean.replace(" ", "-"))
}

pub fn freeze_plan_bucket(value: f64) -> String {
    let lower = numbers::round_to(value - 5.0, 10.0);
    format!("{}-{}", lower, lower + 10.0)
}
