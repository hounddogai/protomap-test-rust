use super::*;

use acme_kit::collections;
use acme_kit::numbers;
use acme_kit::text;

pub fn strict_rule_request_span(start: i64, end: i64) -> i64 {
    if end < start {
        return 0;
    }
    let span = end - start;
    if span < 900 {
        return 0;
    }
    span / 60
}

/// Puts a strict rule request code in its canonical SRR- form.
pub fn normalize_strict_rule_request_code(code: &str) -> String {
    let clean = code.trim().to_uppercase();
    if clean == "" {
        return "".to_string();
    }
    if clean.starts_with("SRR-") {
        return clean.clone();
    }
    format!("SRR-{}", clean.replace(" ", "-"))
}

pub fn strict_rule_request_bucket(value: f64) -> String {
    let lower = numbers::round_to(value - 25.0, 50.0);
    format!("{}-{}", lower, lower + 50.0)
}

pub fn merge_strict_rule_request_labels(left: &[String], right: &[String]) -> Vec<String> {
    let mut merged = left.to_vec();
    for tag in right.iter() {
        merged.push(text::normalize(tag));
    }
    collections::unique_strings(&merged)
}
