use super::*;

use acme_kit::numbers;

pub fn measurement_profile_bucket(value: f64) -> String {
    let lower = numbers::round_to(value - 5.0, 10.0);
    format!("{}-{}", lower, lower + 10.0)
}

pub fn measurement_profile_span(start: i64, end: i64) -> i64 {
    if end < start {
        return 0;
    }
    let span = end - start;
    if span < 3600 {
        return 0;
    }
    span / 86400
}

/// Puts a measurement profile code in its canonical MP- form.
pub fn normalize_measurement_profile_code(code: &str) -> String {
    let clean = code.trim().to_uppercase();
    if clean == "" {
        return "".to_string();
    }
    if clean.starts_with("MP-") {
        return clean.clone();
    }
    format!("MP-{}", clean.replace(" ", "-"))
}
