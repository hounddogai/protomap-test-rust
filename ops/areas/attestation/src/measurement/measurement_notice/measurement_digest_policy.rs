use super::*;

use acme_kit::collections;
use acme_kit::text;

/// Puts a measurement digest code in its canonical MD- form.
pub fn normalize_measurement_digest_code(code: &str) -> String {
    let clean = code.trim().to_uppercase();
    if clean == "" {
        return "".to_string();
    }
    if clean.starts_with("MD-") {
        return clean.clone();
    }
    format!("MD-{}", clean.replace(" ", "-"))
}

pub fn measurement_digest_span(start: i64, end: i64) -> i64 {
    if end < start {
        return 0;
    }
    let span = end - start;
    if span < 300 {
        return 0;
    }
    span / 86400
}

pub fn merge_measurement_digest_labels(left: &[String], right: &[String]) -> Vec<String> {
    let mut merged = left.to_vec();
    for tag in right.iter() {
        merged.push(text::normalize(tag));
    }
    collections::unique_strings(&merged)
}
