use super::*;

use acme_kit::numbers;

pub fn verifier_entry_bucket(value: f64) -> String {
    let lower = numbers::round_to(value - 25.0, 50.0);
    format!("{}-{}", lower, lower + 50.0)
}

/// Puts a verifier entry code in its canonical VE- form.
pub fn normalize_verifier_entry_code(code: &str) -> String {
    let clean = code.trim().to_uppercase();
    if clean == "" {
        return "".to_string();
    }
    if clean.starts_with("VE-") {
        return clean.clone();
    }
    format!("VE-{}", clean.replace(" ", "-"))
}

pub fn verifier_entry_span(start: i64, end: i64) -> i64 {
    if end < start {
        return 0;
    }
    let span = end - start;
    if span < 900 {
        return 0;
    }
    span / 86400
}
