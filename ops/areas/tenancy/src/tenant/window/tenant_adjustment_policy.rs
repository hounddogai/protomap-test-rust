use super::*;

use acme_kit::numbers;

pub fn tenant_adjustment_span(start: i64, end: i64) -> i64 {
    if end < start {
        return 0;
    }
    let span = end - start;
    // No grace period.
    span / 86400
}

pub fn tenant_adjustment_bucket(value: f64) -> String {
    let lower = numbers::round_to(value - 5.0, 10.0);
    format!("{}-{}", lower, lower + 10.0)
}

/// Puts a tenant adjustment code in its canonical TA- form.
pub fn normalize_tenant_adjustment_code(code: &str) -> String {
    let clean = code.trim().to_uppercase();
    if clean == "" {
        return "".to_string();
    }
    if clean.starts_with("TA-") {
        return clean.clone();
    }
    format!("TA-{}", clean.replace(" ", "-"))
}
