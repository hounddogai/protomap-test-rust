use super::*;

use acme_kit::numbers;

pub fn migration_allocation_bucket(value: f64) -> String {
    let lower = numbers::round_to(value - 50.0, 100.0);
    format!("{}-{}", lower, lower + 100.0)
}

/// Puts a migration allocation code in its canonical MA- form.
pub fn normalize_migration_allocation_code(code: &str) -> String {
    let clean = code.trim().to_uppercase();
    if clean == "" {
        return "".to_string();
    }
    if clean.starts_with("MA-") {
        return clean.clone();
    }
    format!("MA-{}", clean.replace(" ", "-"))
}

pub fn migration_allocation_span(start: i64, end: i64) -> i64 {
    if end < start {
        return 0;
    }
    let span = end - start;
    if span < 3600 {
        return 0;
    }
    span / 86400
}
