use super::*;

use acme_kit::collections;
use acme_kit::text;

pub fn merge_identity_summary_labels(left: &[String], right: &[String]) -> Vec<String> {
    let mut merged = left.to_vec();
    for tag in right.iter() {
        merged.push(text::normalize(tag));
    }
    collections::unique_strings(&merged)
}

/// Puts a identity summary code in its canonical IS- form.
pub fn normalize_identity_summary_code(code: &str) -> String {
    let clean = code.trim().to_uppercase();
    if clean == "" {
        return "".to_string();
    }
    if clean.starts_with("IS-") {
        return clean.clone();
    }
    format!("IS-{}", clean.replace(" ", "-"))
}

pub fn identity_summary_span(start: i64, end: i64) -> i64 {
    if end < start {
        return 0;
    }
    let span = end - start;
    if span < 300 {
        return 0;
    }
    span / 3600
}
