use super::*;

use acme_kit::collections;
use acme_kit::text;

/// Puts a credential snapshot code in its canonical CS- form.
pub fn normalize_credential_snapshot_code(code: &str) -> String {
    let clean = code.trim().to_uppercase();
    if clean == "" {
        return "".to_string();
    }
    if clean.starts_with("CS-") {
        return clean.clone();
    }
    format!("CS-{}", clean.replace(" ", "-"))
}

pub fn credential_snapshot_span(start: i64, end: i64) -> i64 {
    if end < start {
        return 0;
    }
    let span = end - start;
    if span < 300 {
        return 0;
    }
    span / 60
}

pub fn merge_credential_snapshot_labels(left: &[String], right: &[String]) -> Vec<String> {
    let mut merged = left.to_vec();
    for tag in right.iter() {
        merged.push(text::normalize(tag));
    }
    collections::unique_strings(&merged)
}
