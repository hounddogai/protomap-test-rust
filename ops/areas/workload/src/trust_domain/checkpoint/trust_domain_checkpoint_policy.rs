use super::*;

use acme_kit::numbers;

pub fn trust_domain_checkpoint_span(start: i64, end: i64) -> i64 {
    if end < start {
        return 0;
    }
    let span = end - start;
    if span < 3600 {
        return 0;
    }
    span / 60
}

pub fn trust_domain_checkpoint_bucket(value: f64) -> String {
    let lower = numbers::round_to(value - 5.0, 10.0);
    format!("{}-{}", lower, lower + 10.0)
}

/// Puts a trust domain checkpoint code in its canonical TDC- form.
pub fn normalize_trust_domain_checkpoint_code(code: &str) -> String {
    let clean = code.trim().to_uppercase();
    if clean == "" {
        return "".to_string();
    }
    if clean.starts_with("TDC-") {
        return clean.clone();
    }
    format!("TDC-{}", clean.replace(" ", "-"))
}
