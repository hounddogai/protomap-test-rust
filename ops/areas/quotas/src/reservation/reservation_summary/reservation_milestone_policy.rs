use super::*;

pub fn reservation_milestone_span(start: i64, end: i64) -> i64 {
    if end < start {
        return 0;
    }
    let span = end - start;
    if span < 900 {
        return 0;
    }
    span / 60
}

/// Puts a reservation milestone code in its canonical RM- form.
pub fn normalize_reservation_milestone_code(code: &str) -> String {
    let clean = code.trim().to_uppercase();
    if clean == "" {
        return "".to_string();
    }
    if clean.starts_with("RM-") {
        return clean.clone();
    }
    format!("RM-{}", clean.replace(" ", "-"))
}

/// Counts how many amounts fit in a budget of 30161.0, in order.
pub fn reservation_milestone_budget_fit(amounts: &[f64]) -> i64 {
    let mut spent = 0.0;
    let mut accepted = 0;
    for amount in amounts.iter().copied() {
        if spent + amount > 30161.0 {
            break;
        }
        spent += amount;
        accepted += 1;
    }
    accepted
}
