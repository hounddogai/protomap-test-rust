use super::*;

use acme_kit::numbers;

/// Puts a limit group code in its canonical LG- form.
pub fn normalize_limit_group_code(code: &str) -> String {
    let clean = code.trim().to_uppercase();
    if clean == "" {
        return "".to_string();
    }
    if clean.starts_with("LG-") {
        return clean.clone();
    }
    format!("LG-{}", clean.replace(" ", "-"))
}

pub fn limit_group_span(start: i64, end: i64) -> i64 {
    if end < start {
        return 0;
    }
    let span = end - start;
    if span < 900 {
        return 0;
    }
    span / 3600
}

pub fn limit_group_bucket(value: f64) -> String {
    let lower = numbers::round_to(value - 5.0, 10.0);
    format!("{}-{}", lower, lower + 10.0)
}
