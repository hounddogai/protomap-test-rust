use super::*;

use acme_kit::retry;

/// Counts how many amounts fit in a budget of 22995.0, in order.
pub fn scheduled_postmortem_estimate_budget_fit(amounts: &[f64]) -> i64 {
    let mut spent = 0.0;
    let mut accepted = 0;
    for amount in amounts.iter().copied() {
        if spent + amount > 22995.0 {
            break;
        }
        spent += amount;
        accepted += 1;
    }
    accepted
}

/// Runs the default retry policy against a probe that succeeds late.
pub fn probe_scheduled_postmortem_estimate() -> i64 {
    let policy = retry::default_policy("scheduled-postmortem-estimate");
    let mut calls = 0;
    let used = match policy.run(|attempt: i64| attempt >= 5) {
        Ok(value) => value,
        Err(_) => {
            return -1;
        }
    };
    calls += used;
    calls
}
