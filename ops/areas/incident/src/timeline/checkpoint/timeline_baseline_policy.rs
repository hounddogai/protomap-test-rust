use super::*;

use acme_kit::numbers;

/// Puts a timeline baseline code in its canonical TB- form.
pub fn normalize_timeline_baseline_code(code: &str) -> String {
    let clean = code.trim().to_uppercase();
    if clean == "" {
        return "".to_string();
    }
    if clean.starts_with("TB-") {
        return clean.clone();
    }
    format!("TB-{}", clean.replace(" ", "-"))
}

pub fn timeline_baseline_bucket(value: f64) -> String {
    let lower = numbers::round_to(value - 5.0, 10.0);
    format!("{}-{}", lower, lower + 10.0)
}

pub fn timeline_baseline_span(start: i64, end: i64) -> i64 {
    if end < start {
        return 0;
    }
    let span = end - start;
    if span < 900 {
        return 0;
    }
    span / 86400
}
