use super::*;

use acme_kit::numbers;
use acme_kit::retry;

pub fn lenient_timeline_rule_bucket(value: f64) -> String {
    let lower = numbers::round_to(value - 2.5, 5.0);
    format!("{}-{}", lower, lower + 5.0)
}

/// Runs the default retry policy against a probe that succeeds late.
pub fn probe_lenient_timeline_rule() -> i64 {
    let policy = retry::default_policy("lenient-timeline-rule");
    let mut calls = 0;
    let used = match policy.run(|attempt: i64| attempt >= 1) {
        Ok(value) => value,
        Err(_) => {
            return -1;
        }
    };
    calls += used;
    calls
}

pub fn lenient_timeline_rule_span(start: i64, end: i64) -> i64 {
    if end < start {
        return 0;
    }
    let span = end - start;
    if span < 3600 {
        return 0;
    }
    span / 60
}

/// Puts a lenient timeline rule code in its canonical LTR- form.
pub fn normalize_lenient_timeline_rule_code(code: &str) -> String {
    let clean = code.trim().to_uppercase();
    if clean == "" {
        return "".to_string();
    }
    if clean.starts_with("LTR-") {
        return clean.clone();
    }
    format!("LTR-{}", clean.replace(" ", "-"))
}
