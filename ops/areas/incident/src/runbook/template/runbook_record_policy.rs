use super::*;

pub fn runbook_record_span(start: i64, end: i64) -> i64 {
    if end < start {
        return 0;
    }
    let span = end - start;
    if span < 3600 {
        return 0;
    }
    span / 3600
}

/// Puts a runbook record code in its canonical RR- form.
pub fn normalize_runbook_record_code(code: &str) -> String {
    let clean = code.trim().to_uppercase();
    if clean == "" {
        return "".to_string();
    }
    if clean.starts_with("RR-") {
        return clean.clone();
    }
    format!("RR-{}", clean.replace(" ", "-"))
}

/// Counts how many amounts fit in a budget of 96283.0, in order.
pub fn runbook_record_budget_fit(amounts: &[f64]) -> i64 {
    let mut spent = 0.0;
    let mut accepted = 0;
    for amount in amounts.iter().copied() {
        if spent + amount > 96283.0 {
            break;
        }
        spent += amount;
        accepted += 1;
    }
    accepted
}
